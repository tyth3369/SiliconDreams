def _exported_at() -> str:
    return datetime.now(UTC).strftime("%Y-%m-%d %H:%M UTC")


def export_filename(conversation: dict[str, Any], extension: str) -> str:
    """Return a short filesystem-safe export name."""
    title = str(conversation.get("title") or "research").strip()
    slug = re.sub(r"[^\w\u4e00-\u9fff-]+", "-", title, flags=re.UNICODE).strip("-_")
    return f"{(slug or 'research')[:64]}.{extension.lstrip('.')}"


def _citation_markdown(citation: dict[str, Any], index: int) -> str:
    display = str(citation.get("display_source") or citation.get("source") or "Source")
    url = safe_external_url(str(citation.get("url") or ""))
    label = f"[{display}]({url})" if url else display
    metadata = [
        str(value) for value in (citation.get("publisher"), citation.get("published_at")) if value
    ]
    if citation.get("trust_tier") and citation.get("source_type") in {"web", "financial"}:
        metadata.append(f"Tier {citation['trust_tier']}")
    suffix = f" - {' | '.join(metadata)}" if metadata else ""
    lines = [f"{index}. **{citation.get('icon', 'SOURCE')}** {label}{suffix}"]
    if citation.get("snippet"):
        quote = str(citation["snippet"]).replace("\n", " ").strip()
        lines.append(f"   > {quote}")
    return "\n".join(lines)


def build_markdown_export(
    conversation: dict[str, Any], messages: list[dict[str, Any]], lang: str = "zh"
) -> str:
    """Create a portable UTF-8 Markdown research record with full provenance."""
    title = conversation.get("title") or ("未命名研究" if lang == "zh" else "Untitled research")
    exported_label = "导出时间" if lang == "zh" else "Exported"
    source_heading = "来源" if lang == "zh" else "Sources"
    role_labels = {
        "user": "用户" if lang == "zh" else "User",
        "assistant": "分析" if lang == "zh" else "Analysis",
        "system": "系统" if lang == "zh" else "System",
    }
    parts = [f"# {title}", "", f"> {exported_label}: {_exported_at()}", ""]
    for message in messages:
        parts.extend(
            [f"## {role_labels.get(message['role'], message['role'])}", "", message["content"], ""]
        )
        citations = message.get("citations") or []
        if citations:
            parts.extend([f"### {source_heading}", ""])
            for index, citation in enumerate(citations, 1):
                parts.extend([_citation_markdown(citation, index), ""])
    parts.extend(["---", "", "Generated by SiliconDreams"])
    return "\n".join(parts).strip() + "\n"


def _inline_markup(text: str) -> str:
    """Convert a small safe subset of Markdown to ReportLab paragraph markup."""
    escaped = escape(text, quote=False)
    escaped = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", escaped)
    escaped = re.sub(r"`([^`]+)`", r"<font name='Courier'>\1</font>", escaped)
    escaped = re.sub(r"\[(\d+)\]", r"<font color='#1557a0'><super>[\1]</super></font>", escaped)
    return escaped


def _table_cells(line: str) -> list[str]:
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def _is_table_separator(line: str) -> bool:
    cells = _table_cells(line)
    return bool(cells) and all(re.fullmatch(r":?-{3,}:?", cell.replace(" ", "")) for cell in cells)


def _markdown_flowables(text: str, styles: dict[str, ParagraphStyle], width: float) -> list[Any]:
    lines = text.splitlines()
    flowables: list[Any] = []
    paragraph_buffer: list[str] = []

    def flush_paragraph() -> None:
        if paragraph_buffer:
            joined = " ".join(part.strip() for part in paragraph_buffer)
            flowables.append(Paragraph(_inline_markup(joined), styles["body"]))
            flowables.append(Spacer(1, 2.5 * mm))
            paragraph_buffer.clear()

    index = 0
    while index < len(lines):
        line = lines[index].rstrip()
        if not line.strip():
            flush_paragraph()
            index += 1
            continue

        if (
            "|" in line
            and index + 1 < len(lines)
            and "|" in lines[index + 1]
            and _is_table_separator(lines[index + 1])
        ):
            flush_paragraph()
            rows = [_table_cells(line)]
            index += 2
            while index < len(lines) and "|" in lines[index] and lines[index].strip():
                rows.append(_table_cells(lines[index]))
                index += 1
            column_count = max(len(row) for row in rows)
            normalized = [row + [""] * (column_count - len(row)) for row in rows]
            cell_style = styles["table"]
            data = [
                [Paragraph(_inline_markup(cell), cell_style) for cell in row] for row in normalized
            ]
            table = Table(data, colWidths=[width / column_count] * column_count, repeatRows=1)
            table.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#16324f")),
                        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                        ("GRID", (0, 0), (-1, -1), 0.35, colors.HexColor("#b7c2cc")),
                        ("VALIGN", (0, 0), (-1, -1), "TOP"),
                        ("LEFTPADDING", (0, 0), (-1, -1), 4),
                        ("RIGHTPADDING", (0, 0), (-1, -1), 4),
                        ("TOPPADDING", (0, 0), (-1, -1), 4),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                        (
                            "ROWBACKGROUNDS",
                            (0, 1),
                            (-1, -1),
                            [colors.white, colors.HexColor("#f3f6f8")],
                        ),
                    ]
                )
            )
            flowables.extend([table, Spacer(1, 3 * mm)])
            continue

        heading = re.match(r"^(#{1,4})\s+(.+)$", line)
        if heading:
            flush_paragraph()
            level = min(len(heading.group(1)), 3)
            flowables.extend(
                [
                    Paragraph(_inline_markup(heading.group(2)), styles[f"heading{level}"]),
                    Spacer(1, 1.5 * mm),
                ]
            )
            index += 1
            continue

        bullet = re.match(r"^\s*[-*]\s+(.+)$", line)
        numbered = re.match(r"^\s*(\d+)[.)]\s+(.+)$", line)
        if bullet or numbered:
            flush_paragraph()
            content = bullet.group(1) if bullet else numbered.group(2)
            marker = "-" if bullet else f"{numbered.group(1)}."
            flowables.append(
                Paragraph(_inline_markup(content), styles["bullet"], bulletText=marker)
            )
            index += 1
            continue

        if line.startswith("> "):
            flush_paragraph()
            flowables.extend(
                [Paragraph(_inline_markup(line[2:]), styles["quote"]), Spacer(1, 2 * mm)]
            )
            index += 1
            continue

        paragraph_buffer.append(line)
        index += 1

    flush_paragraph()
    return flowables


