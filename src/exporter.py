def build_pdf_export(
    conversation: dict[str, Any], messages: list[dict[str, Any]], lang: str = "zh"
) -> bytes:
    """Create an A4 PDF with CJK-safe text, tables, citations and page numbers."""
    buffer = BytesIO()
    page_width, page_height = A4
    margin = 18 * mm
    content_width = page_width - 2 * margin
    styles = _styles()
    title = conversation.get("title") or ("未命名研究" if lang == "zh" else "Untitled research")

    def page_decoration(canvas, document) -> None:
        canvas.saveState()
        canvas.setStrokeColor(colors.HexColor("#d8dde2"))
        canvas.line(margin, page_height - 12 * mm, page_width - margin, page_height - 12 * mm)
        canvas.setFont(FONT_NAME, 7)
        canvas.setFillColor(colors.HexColor("#667788"))
        canvas.drawString(margin, 9 * mm, "SILICON DREAMS")
        canvas.drawRightString(page_width - margin, 9 * mm, str(document.page))
        canvas.restoreState()

    document = BaseDocTemplate(
        buffer,
        pagesize=A4,
        leftMargin=margin,
        rightMargin=margin,
        topMargin=20 * mm,
        bottomMargin=16 * mm,
        title=title,
        author="SiliconDreams",
    )
    frame = Frame(
        document.leftMargin,
        document.bottomMargin,
        document.width,
        document.height,
        id="normal",
    )
    document.addPageTemplates(PageTemplate(id="report", frames=[frame], onPage=page_decoration))

    exported_label = "导出时间" if lang == "zh" else "Exported"
    source_heading = "引用溯源" if lang == "zh" else "Sources"
    role_labels = {
        "user": "用户问题" if lang == "zh" else "User",
        "assistant": "分析回答" if lang == "zh" else "Analysis",
        "system": "系统" if lang == "zh" else "System",
    }
    story: list[Any] = [
        Paragraph(escape(title), styles["title"]),
        Paragraph(f"{exported_label}: {_exported_at()}", styles["meta"]),
        Spacer(1, 7 * mm),
    ]
    for message in messages:
        role = role_labels.get(message["role"], message["role"])
        story.append(Paragraph(escape(role), styles["role"]))
        story.extend(_markdown_flowables(message["content"], styles, content_width))
        citations = message.get("citations") or []
        if citations:
            citation_flowables: list[Any] = [Paragraph(source_heading, styles["heading3"])]
            for index, citation in enumerate(citations, 1):
                display = escape(
                    str(citation.get("display_source") or citation.get("source") or "Source")
                )
                url = safe_external_url(str(citation.get("url") or ""))
                if url:
                    display = (
                        f'<link href="{escape(url, quote=True)}" color="#1557a0">{display}</link>'
                    )
                metadata = [
                    escape(str(value))
                    for value in (citation.get("publisher"), citation.get("published_at"))
                    if value
                ]
                suffix = f" - {' | '.join(metadata)}" if metadata else ""
                citation_flowables.append(
                    Paragraph(
                        f"[{index}] {escape(str(citation.get('icon', 'SOURCE')))} {display}{suffix}",
                        styles["source"],
                    )
                )
                if citation.get("snippet"):
                    citation_flowables.append(
                        Paragraph(escape(str(citation["snippet"])), styles["quote"])
                    )
            story.append(KeepTogether(citation_flowables[:2]))
            story.extend(citation_flowables[2:])
            story.append(Spacer(1, 3 * mm))
    story.append(Paragraph("Generated by SiliconDreams", styles["meta"]))
    document.build(story)
    return buffer.getvalue()
